source(system.file('tinytest/helper_glm_validation.R',package='dbreg'),local=TRUE)
local({
 conn=dbglm_validation_connection(TRUE)
 table=fit=NULL
 on.exit({ if(!is.null(fit)) close(fit); if(!is.null(table)) dbglm_validation_drop(conn,table); DBI::dbDisconnect(conn) })
 initial=dbglm_validation_tables(conn)
 set.seed(586)
 d=data.frame(id=1:180,x=rnorm(180),g=rep(1:9,20),h=rep(1:6,30),w=runif(180,.2,1.2))
 d[['y']]=d[['x']]+sin(d[['g']])+rnorm(180)
 table=dbglm_validation_upload(conn,d)
 policy=dbreg::ssc(K.fixef='none',t.df=7)
 expect_identical(class(policy),class(fixest::ssc()))
 fit=dbreg::feols(y~x|g,conn=conn,table=table,weights=~w,vcov=~h,ssc=policy,lean=TRUE)
 reference=fixest::feols(y~x|g,d,weights=~w,vcov=~h,ssc=policy,notes=FALSE)
 expect_equal(coef(fit),coef(reference),tolerance=1e-8)
 expect_equal(as.numeric(vcov(fit)),as.numeric(vcov(reference)),tolerance=1e-8)
 expect_equal(as.numeric(confint(fit)),as.numeric(as.matrix(confint(reference))),tolerance=1e-8)
 expect_equal(as.numeric(dbreg::coeftable(fit)),as.numeric(as.matrix(fixest::coeftable(reference))),tolerance=1e-8)
 expect_equal(as.numeric(logLik(fit)),as.numeric(logLik(reference)),tolerance=1e-8)
 expect_equal(AIC(fit),AIC(reference),tolerance=1e-8)
 expect_equal(BIC(fit),BIC(reference),tolerance=1e-8)
 expect_equal(dbreg::degrees_freedom(fit,'t'),7)
 expect_identical(fit[['resource_state']],NULL)
 expect_identical(dbglm_validation_tables(conn),sort(c(initial,table)))
})
