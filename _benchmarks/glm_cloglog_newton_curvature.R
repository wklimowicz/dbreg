pkgload::load_all()
source("_benchmarks/glm_databricks_more_helpers.R")
reference=read.csv(commandArgs(TRUE)[[1]])
conn=DBI::dbConnect(duckdb::duckdb(config=list(threads="2",temp_directory="")))
data=data.frame(q=reference[["eta"]],y=reference[["y"]],a=reference[["a"]],o=0)
names(data)=c("q","__dbglm_y","__dbglm_a","__dbglm_o")
DBI::dbWriteTable(conn,"curvature",data)
experiment=glm_experiment_newton(Inf)
sql=dbreg:::dbglm_working_sql("curvature",character(),numeric(),"cloglog",eta="q")
values=tryCatch(DBI::dbGetQuery(conn,paste0(sql,"SELECT w FROM working"))[["w"]],finally=experiment[["restore"]]())
reference[["computed"]]=values
reference[["relative_error"]]=abs(values/reference[["curvature"]]-1)
print(reference[order(reference[["relative_error"]],decreasing=TRUE)[1:5],])
stopifnot(all(is.finite(values)),all(values>0),max(reference[["relative_error"]])<1e-7)
write.csv(reference,commandArgs(TRUE)[[2]],row.names=FALSE)
DBI::dbDisconnect(conn,shutdown=TRUE)
