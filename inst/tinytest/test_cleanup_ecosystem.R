local({
  exports = getNamespaceExports("dbreg")
  expect_equal(intersect(exports, c("feols", "feglm", "i", "ssc", "degrees_freedom", "coeftable", "se", "tstat", "pvalue", "obs")), character())
  set.seed(987)
  d = data.frame(x = rnorm(240), z = rnorm(240), g = rep(1:12, each = 20), o = rnorm(240, sd = 0.1))
  d[["y"]] = 0.4 * d[["x"]] + sin(d[["g"]]) + cos(d[["g"]]) * d[["z"]] + d[["o"]] + rnorm(240)
  d[["x"]][1] = NA_real_
  for (strategy in c("demean", "compress")) {
    fit = dbreg::dbreg(y ~ x | g[z], data = d, offset = ~o, strategy = strategy, retain = "all")
    expect_true(!"list" %in% class(fit))
    table = fixest::coeftable(fit)
    expect_equal(as.numeric(table[, 1L]), unname(stats::coef(fit)))
    expect_identical(rownames(table), names(stats::coef(fit)))
    expect_equal(fixest::se(fit), sqrt(diag(stats::vcov(fit))))
    expect_equal(as.numeric(fixest::tstat(fit)), as.numeric(table[, 3L]))
    expect_identical(names(fixest::tstat(fit)), rownames(table))
    expect_equal(as.numeric(fixest::pvalue(fit)), as.numeric(table[, 4L]))
    expect_identical(names(fixest::pvalue(fit)), rownames(table))
    effects = fixest::fixef(fit)
    expected = 0.4 * d[["x"]]
    reconstructed = stats::coef(fit)[["x"]] * d[["x"]] + effects[["g"]][as.character(d[["g"]])] +
      effects[["g[[z]]"]][as.character(d[["g"]])] * d[["z"]] + d[["o"]]
    expect_equal(as.numeric(reconstructed), stats::predict(fit, d), tolerance = 1e-7)
    rows = generics::augment(fit)
    expect_equal(nrow(rows), stats::nobs(fit))
    expect_equal(rows[[".fitted"]], stats::fitted(fit), tolerance = 1e-7)
    expect_equal(rows[[".resid"]], stats::residuals(fit), tolerance = 1e-7)
    provided = generics::augment(fit, data = d)
    expect_equal(provided[[".fitted"]], rows[[".fitted"]])
    tidy = generics::tidy(fit, vcov = "hc1", conf.int = TRUE)
    expect_equal(tidy[["std.error"]], sqrt(diag(stats::vcov(fit, vcov = "hc1"))), check.attributes = FALSE)
    close(fit)
  }
  compact = dbreg::dbreg(y ~ x | g, data = d)
  expect_error(fixest::fixef(compact), "retain")
  expect_error(generics::augment(compact), "retain")
  d[["b"]] = stats::rbinom(240, 1, stats::plogis(0.2 * replace(d[["x"]], 1, 0)))
  fit = dbreg::dbglm(b ~ x | g, data = d, family = stats::binomial("logit"), retain = "all")
  rows = generics::augment(fit)
  expect_equal(rows[[".fitted"]], stats::fitted(fit), tolerance = 1e-7)
  expect_equal(rows[[".resid"]], stats::residuals(fit), tolerance = 1e-7)
  expect_identical(colnames(fixest::coeftable(fit))[[3L]], "z value")
  close(fit)
})
local({
  set.seed(988)
  d = data.frame(x = rnorm(640), g = rep(1:32, each = 20), h = sample.int(8, 640, TRUE))
  d[["y"]] = 0.3 * d[["x"]] + sin(d[["g"]]) + cos(d[["h"]]) + rnorm(640)
  d[["dbreg_augment_position__"]] = seq_len(nrow(d)) + 1000L
  d[["dbreg_augment_fitted__"]] = "original"
  d[["dbreg_augment_resid__"]] = -1
  old = options(dbreg.prediction_max_entries = 64)
  on.exit(options(old), add = TRUE)
  conn = DBI::dbConnect(duckdb::duckdb())
  on.exit(DBI::dbDisconnect(conn, shutdown = TRUE), add = TRUE)
  DBI::dbWriteTable(conn, "ecosystem_sample", d)
  before = DBI::dbListTables(conn)
  fit = dbreg::dbreg(y ~ x | g + h, conn = conn, table = "ecosystem_sample", row_id = "dbreg_augment_position__", retain = "all")
  on.exit(close(fit), add = TRUE)
  expect_identical(fit[["fitted_state"]][["prediction"]][["storage"]], "database")
  effects = fixest::fixef(fit)
  prediction = unname(stats::coef(fit)[["x"]] * d[["x"]] + effects[["g"]][as.character(d[["g"]])] + effects[["h"]][as.character(d[["h"]])])
  expect_equal(prediction, stats::predict(fit, d), tolerance = 1e-7)
  rows = generics::augment(fit)
  expect_equal(sort(rows[["dbreg_augment_position__"]]), d[["dbreg_augment_position__"]])
  expect_identical(rows[["dbreg_augment_fitted__"]], rep("original", nrow(d)))
  expect_equal(rows[[".fitted"]], stats::predict(fit, rows), tolerance = 1e-7)
  expect_equal(rows[[".resid"]], rows[["y"]] - rows[[".fitted"]], tolerance = 1e-7)
  if (requireNamespace("insight", quietly = TRUE)) {
    expect_equal(insight::get_varcov(fit, vcov = "HC1"), stats::vcov(fit, vcov = "hc1"))
    expect_equal(insight::get_varcov(fit, vcov = "vcovCL", vcov_args = list(cluster = ~g)), stats::vcov(fit, cluster = ~g))
    expect_error(insight::get_varcov(fit, vcov = "HC3"), "Unsupported covariance")
  }
  if (requireNamespace("modelsummary", quietly = TRUE) && requireNamespace("broom", quietly = TRUE)) {
    for (request in list("HC1", ~g)) {
      estimates = modelsummary::get_estimates(fit, vcov = request)
      expect_equal(estimates[["std.error"]], sqrt(diag(stats::vcov(fit, vcov = request))), check.attributes = FALSE)
      expect_equal(estimates[["conf.low"]], stats::confint(fit, vcov = request)[, 1L], check.attributes = FALSE)
    }
  }
  covariance = stats::vcov(fit, vcov = "hc1")
  tidied = generics::tidy(fit, vcov = covariance, conf.int = TRUE)
  expect_equal(tidied[["std.error"]], sqrt(diag(covariance)), check.attributes = FALSE)
  expect_equal(tidied[["conf.low"]], stats::confint(fit, vcov = "hc1")[, 1L], check.attributes = FALSE)
  expect_error(generics::tidy(fit, vcov = matrix(1, 2, 2)), "symmetric covariance")
  plot_file = tempfile(fileext = ".pdf")
  grDevices::pdf(plot_file)
  plot = fixest::coefplot(fit)
  grDevices::dev.off()
  unlink(plot_file)
  expect_equal(as.numeric(plot[["prms"]][["estimate"]]), as.numeric(stats::coef(fit)))
  close(fit)
  expect_identical(DBI::dbListTables(conn), before)
  expect_error(fixest::fixef(fit), "released")
})
