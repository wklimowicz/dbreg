local({
  set.seed(915)
  d = data.frame(x = rnorm(240), c1 = sample.int(12, 240, TRUE), c2 = sample.int(8, 240, TRUE))
  d[["y"]] = 1 + d[["x"]] + rnorm(240)
  fit = dbreg::dbreg(y ~ x, data = d, retain = "inference", vcov = ~c1)
  on.exit(close(fit))
  changed = summary(fit, vcov = ~c2)
  reference = fixest::feols(y ~ x, data = d, vcov = ~c2, notes = FALSE)
  expect_equal(c(stats::vcov(changed)), c(stats::vcov(reference)), tolerance = 1e-10)
  expect_identical(changed[["cluster_var"]], "c2")
  expect_equal(unname(changed[["n_clusters"]]), 8)
  expect_equal(changed[["n_params"]], attr(changed[["vcov"]], "n_params"))
  hetero = summary(fit, vcov = "hc1")
  expect_identical(hetero[["cluster_var"]], NULL)
  expect_identical(hetero[["n_clusters"]], NULL)
  expect_identical(hetero[["vcov_type"]], "hc1")
  expect_equal(nrow(dbreg::glance(changed)), 1L)
  expect_identical(dbreg::glance(changed)[["cluster"]], "c2")
  expect_true(is.na(dbreg::glance(hetero)[["cluster"]]))
  iid = dbreg::dbreg(y ~ x, data = d, retain = "inference")
  on.exit(close(iid), add = TRUE)
  twoway = summary(iid, vcov = ~c1 + c2)
  expect_identical(twoway[["cluster_var"]], c("c1", "c2"))
  expect_equal(unname(twoway[["n_clusters"]]), c(12, 8))
  expect_equal(twoway[["df_t"]], 7)
  expect_equal(nrow(dbreg::glance(twoway)), 1L)
  expect_identical(dbreg::glance(twoway)[["cluster"]], "c1;c2")
  expect_identical(dbreg::glance(twoway)[["n.clusters"]], "12;8")
  expect_identical(dbreg::glance(twoway)[["ssc"]],
    "K.adj=TRUE;K.fixef=full;K.exact=FALSE;G.adj=TRUE;G.df=min;t.df=min")
  custom = summary(iid, vcov = ~c2, ssc = list(K.adj = FALSE, G.adj = FALSE))
  expect_identical(custom[["ssc"]][["K.adj"]], FALSE)
  expect_identical(custom[["ssc"]][["G.adj"]], FALSE)
  reference = fixest::feols(y ~ x, data = d, vcov = ~c2,
    ssc = fixest::ssc(K.adj = FALSE, G.adj = FALSE), notes = FALSE)
  expect_equal(c(stats::vcov(custom)), c(stats::vcov(reference)), tolerance = 1e-10)

  d[["b"]] = stats::rbinom(nrow(d), 1, stats::plogis(0.2 * d[["x"]]))
  glm = dbreg::dbglm(b ~ x, data = d, family = stats::binomial(), retain = "inference", vcov = ~c1)
  on.exit(close(glm), add = TRUE)
  changed_glm = summary(glm, vcov = ~c2)
  expect_identical(changed_glm[["cluster_var"]], "c2")
  expect_equal(unname(changed_glm[["n_clusters"]]), 8)
  hetero_glm = summary(glm, vcov = "hc1")
  expect_identical(hetero_glm[["cluster_var"]], NULL)
  expect_identical(hetero_glm[["n_clusters"]], NULL)

})
