source(system.file("tinytest/helper_glm_reference.R",package="dbreg"),local=TRUE)
source(system.file("tinytest/helper_glm_validation.R",package="dbreg"),local=TRUE)
source(system.file("tinytest/helper_compat_api.R",package="dbreg"),local=TRUE)
local({
  conn = dbglm_validation_connection()
  on.exit(DBI::dbDisconnect(conn,shutdown=TRUE))
  dbreg_test_compat_api(conn)
  set.seed(583)
  d = data.frame(x=rnorm(160),z=rnorm(160),g=rep(1:8,20),o=rnorm(160),w=runif(160))
  d[["y"]] = d[["x"]]+d[["o"]]+sin(d[["g"]])+rnorm(160)
  d[["w"]][2] = 0
  d[["y"]][3] = NA_real_
  keep = rep(c(TRUE,FALSE,TRUE,TRUE),40)
  keep[4] = NA
  fit = dbreg::feols(y~x+z|g,d,weights=d[["w"]],offset=d[["o"]],subset=keep)
  ref = fixest::feols(y~x+z|g,d,weights=~w,offset=~o,subset=keep,notes=FALSE)
  expect_identical(dbreg::obs(fit),fixest::obs(ref))
  expect_equal(predict(fit),predict(ref),tolerance=1e-7)
  expect_equal(predict(fit,sample="original"),predict(ref,sample="original"),tolerance=1e-7)
  expect_equal(predict(fit,d,offset=~o),predict(ref,d),tolerance=1e-7)
  expect_error(predict(fit,d),"vector offset.*explicit offset")
  expect_equal(as.numeric(dbreg::coeftable(fit,cluster=~g)),as.numeric(as.matrix(fixest::coeftable(ref,cluster=~g))),tolerance=1e-6)
  close(fit)
  for (indices in list(5:150,-c(1:6,200))) {
    fit = dbreg::feols(y~x,d,weights=~w,offset=~o,subset=indices,lean=TRUE)
    ref = fixest::feols(y~x,d,weights=~w,offset=~o,subset=indices,notes=FALSE)
    expect_equal(coef(fit),coef(ref),tolerance=1e-8)
    expect_equal(AIC(fit),AIC(ref),tolerance=1e-8)
    expect_equal(predict(fit,d),predict(ref,d),tolerance=1e-7)
    expect_error(predict(fit),"lean=TRUE")
    expect_error(dbreg::obs(fit),"state|resource|unavailable")
    close(fit)
  }
  fit = dbreg::feols(y~x+z,d,fixef="g",notes=FALSE)
  ref = fixest::feols(y~x+z,d,fixef="g",notes=FALSE)
  for (selector in list(list(keep="!Intercept",order="z"),list(drop="x",order="!z"),list(keep="%x"))) {
    expect_equal(do.call(coef,c(list(fit),selector)),do.call(coef,c(list(ref),selector)),tolerance=1e-8)
  }
  expect_equal(as.numeric(dbreg::se(ref)),as.numeric(fixest::se(ref)))
  changed = summary(fit,ssc=dbreg::ssc(K.fixef="none"))
  changed_ref = summary(ref,ssc=fixest::ssc(K.fixef="none"))
  expect_equal(as.numeric(vcov(changed,cluster=~g)),as.numeric(vcov(changed_ref,cluster=~g)),tolerance=1e-8)
  close(fit)
  expect_error(dbreg::feols(y~x,conn=conn,table="absent",weigths="w"),"Unused arguments:.*weigths")
  expect_error(dbreg::feols(y~x,conn=conn,table="absent",vcov="bad"),"Unsupported covariance")
  expect_error(dbreg::feglm(y~x,conn=conn,table="absent",vcov=~g+z),"one-way GLM")
  expect_error(dbreg::feols(y~x,conn=conn,table="absent",weights=1:5),"Positional weights")
  expect_error(dbreg::feols(y~x,d,subset=c(1,1,2)),"unique")
  expect_error(dbreg::feols(y~x,d,subset=c(2,1)),"original order")
  expect_error(dbreg::feols(y~x,d,subset=rep(TRUE,3)),"original data size")
  expect_error(dbreg::feols(y~x,d,weights=~log(w)),"formulas must name one column")
  expect_error(dbreg::ssc(K.exact=TRUE),"Unsupported")
  expect_identical(class(dbreg::ssc()),class(fixest::ssc()))
  expect_equal(as.numeric(vcov(ref,ssc=dbreg::ssc())),as.numeric(vcov(ref,ssc=fixest::ssc())),tolerance=1e-10)
  d[["b"]] = rbinom(nrow(d),1,plogis(.2*d[["x"]]))
  for (family in list(gaussian(),binomial("cloglog"))) {
    fml = if (family[["family"]]=="gaussian") y~x+z else b~x+z
    fit = dbreg::feglm(fml,d,family=family,weights=~w,offset=~o,subset=keep,lean=TRUE,notes=FALSE)
    ref = dbglm_reference_feglm(fml,d,family=family,weights=~w,offset=~o,subset=keep)
    expect_equal(coef(fit),coef(ref),tolerance=1e-6,scale=1)
    expect_equal(predict(fit,d),predict(ref,d),tolerance=1e-6)
    expect_equal(as.numeric(logLik(fit)),as.numeric(logLik(ref)),tolerance=1e-6)
    expect_equal(AIC(fit),AIC(ref),tolerance=1e-6)
    expect_identical(fit[["resource_state"]],NULL)
    if (family[["family"]]=="binomial") {
      rows = fixest::obs(ref)
      X = model.matrix(~x+z,d[rows,])
      eta = as.vector(X%*%coef(fit))+d[["o"]][rows]
      mu = family[["linkinv"]](eta)
      score = colSums(X*(d[["w"]][rows]*family[["mu.eta"]](eta)*(d[["b"]][rows]-mu)/(mu*(1-mu))))
      expect_true(max(abs(score))<1e-6)
    }
    close(fit)
  }
  fit = dbreg::feols(y~x+z,d,offset=d[["o"]],lean=TRUE)
  saved = tempfile(fileext=".rds")
  on.exit(unlink(saved),add=TRUE)
  saveRDS(fit,saved)
  restored = readRDS(saved)
  expect_equal(predict(restored,d,offset=~o),predict(fit,d,offset=~o))
  expect_identical(logLik(restored),logLik(fit))
  expect_true(as.numeric(object.size(restored))<250000)
  close(fit)
  expect_identical(DBI::dbListTables(conn),character())
})
