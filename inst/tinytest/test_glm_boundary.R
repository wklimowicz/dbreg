library(dbreg)
library(DBI)
cb <- dbConnect(duckdb::duckdb(config=list(temp_directory="")))
db <- data.frame(x=rep(c(-1,1),each=12),y=rep(c(0,1),each=12))
expect_error(dbglm(y~x,conn=cb,data=db,family=binomial('logit')),'boundary|halving|converge')
expect_warning(mb <- dbglm(y~x,conn=cb,data=db,family=binomial('logit'),separation='prediction'),'boundary probabilities')
expect_false(mb$converged)
expect_false(mb$finite_mle)
expect_true(all(is.na(vcov(mb))))
expect_true(all(is.na(mb$coeftable[,c('std.error','statistic','p.value')])))
expect_true(max(abs(predict(mb,db,type='response')-db$y))<1e-7)
expect_false(glance(mb)$finite.mle)
expect_true(is.na(AIC(mb)))
expect_true(is.na(BIC(mb)))
expect_error(dbglm(y~x|x,conn=cb,data=db,separation='prediction'),'no-FE')
expect_equal(length(dbListTables(cb)),0L)
dbDisconnect(cb,shutdown=TRUE)
