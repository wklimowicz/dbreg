library(dbreg)
library(fixest)
library(DBI)
cm <- dbConnect(duckdb::duckdb(config=list(temp_directory="")))
set.seed(1412)
dm <- data.frame(f=rep(1:4096,each=2),g=sample(1:2,8192,TRUE),x=rnorm(8192),y=rep(0:1,4096))
mm <- dbglm(y~x|f+g,conn=cm,data=dm,family=binomial("logit"),
  control=dbglm_control(projection_method="sql"))
source(system.file('tinytest/helper_glm_reference.R',package='dbreg'),local=TRUE)
rmany <- dbglm_reference_feglm(y~x|f+g,dm,family=binomial('logit'))
expect_identical(names(coef(mm)),names(coef(rmany)))
expect_true(all(abs(coef(mm)-coef(rmany))<=1e-7+1e-6*abs(coef(rmany))))
expect_true(all(abs(vcov(mm)-vcov(rmany))<=1e-8+1e-5*abs(vcov(rmany))))
expect_equal(nobs(mm),nobs(rmany))
expect_equal(mm$n_params_model,rmany$nparams)
expect_true(mm$score_max<=mm$control$score_tol)
expect_identical(mm$projection_method,"cg")
for(family in list(binomial("logit"),binomial("probit"),binomial("cloglog"),poisson())) {
 dd <- dm
 if(family$family=="poisson")dd$y <- rep(1:2,4096)
 # A tiny dense cap forces the FE-level PCG path that moments would pre-empt.
 saved <- options(dbreg.glm_fe_dense_max=0)
 fast <- dbglm(y~x|f+g,conn=cm,data=dd,family=family)
 options(saved)
 ref <- dbglm_reference_feglm(y~x|f+g,dd,family=family)
 expect_identical(fast$projection_method,"bounded_pcg")
 expect_true(max(abs(coef(fast)-coef(ref)))<1e-6)
 expect_true(max(abs(vcov(fast)-vcov(ref)))<1e-6)
 expect_true(fast$score_max<=fast$control$score_tol)
 expect_true(fast$projection_residual<=fast$control$fe_tol)
 expect_equal(length(dbListTables(cm)),0L)
}
expect_equal(length(dbListTables(cm)),0L)
dbDisconnect(cm,shutdown=TRUE)
