local({
  conn = DBI::dbConnect(duckdb::duckdb())
  on.exit(DBI::dbDisconnect(conn, shutdown = TRUE))
  set.seed(11147)
  d = expand.grid(g = 1:4, h = 1:3, k = 1:2, x = c(-1, 1), rep = 1:6)
  d[["w"]] = runif(nrow(d), .25, 2)
  d[["cl"]] = d[["g"]] + d[["k"]]
  eta = -.2 + .4 * d[["x"]] + cos(d[["g"]]) / 5
  d[["y"]] = rbinom(nrow(d), 1, binomial("cloglog")[["linkinv"]](eta))
  fit = function(method, ...) dbglm(y ~ x | g + h + k, conn = conn, data = d,
    family = binomial("cloglog"), weights = ~w, vcov = ~cl, strategy = "compress",
    ssc = "full", control = dbglm_control(projection_method = method, score_tol = 1e-9, ...))
  ref = fit("auto")
  sql = fit("sql")
  expect_identical(ref[["projection_method"]], "bounded_moments")
  expect_identical(sql[["projection_method"]], "sql_cg")
  expect_equal(coef(sql), coef(ref), tolerance = 1e-9)
  expect_equal(as.numeric(vcov(sql)), as.numeric(vcov(ref)), tolerance = 1e-9)
  expect_equal(as.numeric(logLik(sql)), as.numeric(logLik(ref)), tolerance = 1e-10)
  expect_true(sql[["converged"]] && max(sql[["score_max"]], sql[["fe_score_max"]]) <= 1e-9)
  expect_identical(DBI::dbListTables(conn), character())
  previous = options(dbreg.fe_dense_max = 1L)
  fallback = fit("auto")
  duckdb_fallback = fit("duckdb_bounded")
  options(previous)
  expect_identical(fallback[["projection_method"]], "sql_cg")
  expect_identical(fallback[["projection_diagnostics"]][["reason"]], "system_limit")
  expect_equal(coef(fallback), coef(sql), tolerance = 1e-10)
  expect_identical(duckdb_fallback[["projection_method"]], "sql_cg")
  expect_identical(duckdb_fallback[["projection_diagnostics"]][["reason"]], "system_limit")
  expect_equal(coef(duckdb_fallback), coef(sql), tolerance = 1e-10)
  partial = fit("sql", glm_max_iter = 1L, tolerate_max_iter = TRUE)
  expect_false(partial[["converged"]])
  expect_identical(partial[["stop_reason"]], "max_iter")
  expect_identical(DBI::dbListTables(conn), character())
})
