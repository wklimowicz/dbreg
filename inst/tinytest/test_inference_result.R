local({
  set.seed(11011)
  d = data.frame(x = stats::rnorm(240), g = rep(seq_len(12), each = 20), h = rep(seq_len(8), 30))
  d[["y"]] = 1 + d[["x"]] + stats::rnorm(240)
  d[["b"]] = stats::rbinom(240, 1, stats::plogis(d[["x"]]))
  fit = dbreg::dbglm(b ~ x | g, data = d, family = stats::binomial(), retain = "inference", ssc = "full")
  on.exit(close(fit))
  changed = summary(fit, vcov = "hc1", ssc = list(K.fixef = "none", t.df = 4))
  reference = fixest::feglm(b ~ x | g, data = d, family = stats::binomial(),
    vcov = "hetero", ssc = fixest::ssc(K.fixef = "none", t.df = 4), fixef.rm = "none", glm.tol = 1e-12, notes = FALSE)
  expect_equal(c(stats::vcov(changed)), c(stats::vcov(reference)), tolerance = 1e-6)
  expect_equal(changed[["n_params_vcov"]], 1)
  expect_equal(changed[["n_params_vcov"]], attr(stats::vcov(changed), "df.K"))
  expect_equal(changed[["n_params_model"]], fit[["n_params_model"]])
  expect_equal(stats::df.residual(changed), stats::df.residual(fit))
  expect_equal(stats::logLik(changed), stats::logLik(fit))
  expect_equal(stats::coef(changed), stats::coef(fit))
  expect_equal(changed[["coeftable"]][, "p.value"], 2 * stats::pnorm(-abs(changed[["coeftable"]][, "statistic"])))
  expect_identical(changed[["inference_result"]][["distribution"]], "normal")

  ols = dbreg::dbreg(y ~ x | g, data = d, retain = "inference", strategy = "demean")
  on.exit(close(ols), add = TRUE)
  clustered = summary(ols, vcov = ~g^h)
  expect_identical(clustered[["inference_result"]][["clusters"]], list(c("g", "h")))
  extracted = stats::vcov(clustered)
  for (field in c("type", "vcov_type", "cluster_var", "n_clusters", "df_t", "df.t", "df.K", "ssc", "repair")) {
    expect_equal(attr(extracted, field), attr(clustered[["vcov"]], field))
  }
  hetero = summary(clustered, vcov = "hc1")
  expect_identical(hetero[["cluster_var"]], NULL)
  expect_identical(hetero[["n_clusters"]], NULL)
  expect_identical(attr(stats::vcov(hetero), "cluster_var"), NULL)
  expect_identical(summary(hetero, ssc = list(t.df = 3))[["vcov_type"]], "hc1")

  empty_data = data.frame(y = rep(c(1, 2, 4, 3), 5), g = rep(seq_len(5), each = 4))
  empty_fit = dbreg::dbreg(y ~ 1 | g, data = empty_data, retain = "inference")
  on.exit(close(empty_fit), add = TRUE)
  empty_summary = summary(empty_fit, vcov = "hc1")
  expect_identical(dim(stats::vcov(empty_summary)), c(0L, 0L))
  expect_equal(length(stats::coef(empty_summary)), 0L)
  expect_equal(empty_summary[["n_params"]], empty_fit[["n_params"]])

  for (family in c("gaussian", "binomial")) {
    empty_data[["y"]] = if (family == "binomial") rep(c(0, 1, 1, 0), 5) else rep(c(1, 2, 4, 3), 5)
    empty_glm = dbreg::dbglm(y ~ 1 | g, data = empty_data, family = family, retain = "inference")
    empty_glm_summary = summary(empty_glm, vcov = "hc1")
    expect_identical(dim(stats::vcov(empty_glm_summary)), c(0L, 0L))
    expect_equal(length(stats::coef(empty_glm_summary)), 0L)
    close(empty_glm)
  }

  V = Matrix::Diagonal(x = c(4, 9))
  dimnames(V) = list(c("a", "b"), c("a", "b"))
  attr(V, "rss") = 18
  record = dbreg:::new_inference_result(V, "iid", c("a", "b"), list(), NULL,
    dbreg:::inference_ssc("full"), 2, 7, "t")
  projected = dbreg:::inference_covariance(record)
  expect_identical(class(projected), class(V))
  expect_equal(c(as.matrix(projected)), c(4, 0, 0, 9))
  expect_identical(attr(projected, "repair"), NULL)
  matrix_object = structure(list(inference_result = record, vcov = projected,
    coeftable = matrix(0, 2, 4, dimnames = list(c("a", "b"), NULL))), class = "dbreg")
  ordinary = stats::vcov(matrix_object)
  expect_identical(class(ordinary), class(V))
  expect_equal(c(as.matrix(ordinary)), c(4, 0, 0, 9))
  expect_equal(attr(ordinary, "df.t"), 7)
  expect_identical(attr(ordinary, "repair"), NULL)
  subset = dbreg:::inference_covariance(record, "b")
  expect_equal(as.numeric(subset), 9)
  expect_equal(attr(subset, "df.t"), 7)
  expect_equal(attr(subset, "rss"), 18)
  # Public dummy labels can coincide with a distinct source regressor label.
  collision_data = data.frame(grp = rep(c("a", "b"), 100), grpb = stats::rnorm(200))
  collision_data[["y"]] = 2 + 3 * (collision_data[["grp"]] == "b") - 0.7 * collision_data[["grpb"]] + stats::rnorm(200)
  collision_fit = dbreg::dbreg(y ~ grp + grpb, data = collision_data,
    strategy = "moments", retain = "inference")
  on.exit(close(collision_fit), add = TRUE)
  collision_summary = summary(collision_fit, vcov = "hc1")
  linear_reference = stats::lm(y ~ grp + grpb, data = collision_data)
  design = stats::model.matrix(linear_reference)
  inverse = solve(crossprod(design))
  scores = design * as.numeric(stats::residuals(linear_reference))
  reference_covariance = inverse %*% crossprod(scores) %*% inverse * nrow(design) / (nrow(design) - ncol(design))
  reference_errors = sqrt(diag(reference_covariance))
  reference_statistics = stats::coef(linear_reference) / reference_errors
  reference_pvalues = 2 * stats::pt(-abs(reference_statistics), nrow(design) - ncol(design))
  expect_true(anyDuplicated(names(stats::coef(collision_fit))) > 0L)
  expect_equal(c(stats::vcov(collision_summary)), c(reference_covariance), tolerance = 1e-10)
  expect_equal(as.numeric(collision_summary[["coeftable"]][, "estimate"]), as.numeric(stats::coef(linear_reference)), tolerance = 1e-10)
  expect_equal(as.numeric(collision_summary[["coeftable"]][, "std.error"]), as.numeric(reference_errors), tolerance = 1e-10)
  expect_equal(as.numeric(collision_summary[["coeftable"]][, "statistic"]), as.numeric(reference_statistics), tolerance = 1e-10)
  expect_equal(as.numeric(collision_summary[["coeftable"]][, "p.value"]), as.numeric(reference_pvalues), tolerance = 1e-10)
  expect_equal(stats::coef(collision_summary), stats::coef(collision_fit), tolerance = 1e-10)
  expect_equal(stats::nobs(collision_summary), stats::nobs(collision_fit))

})
