source(system.file("tinytest/helper_glm_validation.R", package = "dbreg"), local = TRUE)
source(system.file("tinytest/helper_linear_offset.R", package = "dbreg"), local = TRUE)
local({
  conn = dbglm_validation_connection()
  on.exit(DBI::dbDisconnect(conn, shutdown = TRUE))
  dbreg_test_linear_offset(conn)

  set.seed(542)
  d = data.frame(x = rnorm(80), g = rep(1:8, 10), o = rnorm(80))
  d[["y"]] = d[["o"]] + d[["x"]] + rnorm(80)
  d[["o"]][1:3] = c(NA_real_, Inf, NaN)
  fit = dbreg(y ~ x | g, data = d, offset = "o", retain = "all", diagnostics = TRUE)
  ref = fixest::feols(y ~ x | g, data = d[is.finite(d[["o"]]), ], offset = ~o, fixef.rm = "none", notes = FALSE)
  expect_equal(coef(fit), coef(ref), tolerance = 1e-8)
  expect_identical(stats::case.names(fit), 4:80)
  expect_identical(length(predict(fit, sample = "original")), 80L)
  expect_identical(which(is.na(predict(fit, sample = "original"))), 1:3)
  expected = predict(ref, d)
  expected[!is.finite(d[["o"]])] = NA_real_
  expect_equal(predict(fit, d), expected, tolerance = 1e-7)
  expect_identical(fit[["sample_diagnostics"]][["n_input"]], 80)
  close(fit)
  expect_equal(predict(fit, d), expected, tolerance = 1e-7)
  expect_error(dbreg(y ~ x, data = d, offset = ~o + x), "offset.*must name")
  bad = d; bad[["o"]] = "bad"
  expect_error(dbreg(y ~ x, data = bad, offset = "o"), "must be numeric")
  compact = dbreg(y ~ x | g, data = d, offset = "o", strategy = "compress")
  expect_error(predict(compact), "newdata or retain")
  expect_error(predict(compact, d[setdiff(names(d), "o")]), "missing required")
  same = dbreg(y ~ x + y, data = d, offset = "y", strategy = "moments")
  expect_equal(unname(coef(same)), c(0,0,0), tolerance = 1e-8)
})
