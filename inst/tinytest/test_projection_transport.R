source(system.file("tinytest/helper_glm_validation.R", package = "dbreg"), local = TRUE)
source(system.file("tinytest/helper_projection_transport.R", package = "dbreg"), local = TRUE)
local({
  conn = dbglm_validation_connection()
  on.exit(DBI::dbDisconnect(conn, shutdown = TRUE))
  dbreg_test_projection_transport(conn)
  attempt = dbreg:::projection_attempt("test", dbreg:::projection_abort("transfer_limit", "Capacity declined", list(required = 10)))
  expect_identical(attempt[["status"]], "declined")
  expect_identical(attempt[["reason"]], "transfer_limit")
  expect_equal(attempt[["details"]][["required"]], 10)
  expect_error(dbreg:::projection_attempt("test", stop("deliberate query failure")), "deliberate query failure")
  limits = dbreg:::projection_limits()
  limits[["transfer_cells"]] = 8
  budget = list2env(list(rows = 0, cells = 0), parent = emptyenv())
  sql = "SELECT 1 AS id,2.0 AS h UNION ALL SELECT 2 AS id,3.0 AS h"
  first = dbreg:::projection_fetch(conn, sql, budget, 2L, limits)
  expect_equal(nrow(first), 2L)
  expect_equal(budget[["cells"]], 6)
  attempt = dbreg:::projection_attempt("test", dbreg:::projection_fetch(conn, sql, budget, 2L, limits))
  expect_identical(attempt[["reason"]], "transfer_limit")
  old = options(dbreg.projection_max_bytes = 1)
  fit = tryCatch(dbreg(mpg ~ hp | cyl + gear, data = mtcars, strategy = "demean"), finally = options(old))
  expect_identical(fit[["projection_diagnostics"]][[1L]][["reason"]], "system_limit")
  reference = fixest::feols(mpg ~ hp | cyl + gear, mtcars, fixef.rm = "none", ssc = fixest::ssc(K.fixef = "full"))
  expect_equal(coef(fit), coef(reference), tolerance = 1e-7)
  saved = options(dbreg.ap_solver = "auto", dbreg.glm_fe_dense_max = 0,
    dbreg.ap_method = NULL, dbreg.duckdb_ap_method = NULL)
  fit = tryCatch(dbreg(mpg ~ hp | cyl + gear, data = mtcars, strategy = "demean", weights = "wt"), finally = options(saved))
  reference = fixest::feols(mpg ~ hp | cyl + gear, mtcars, weights = ~wt,
    fixef.rm = "none", ssc = fixest::ssc(K.fixef = "full"))
  expect_identical(fit[["ap_method"]], "bounded_pcg")
  expect_equal(coef(fit), coef(reference), tolerance = 1e-7)
  expect_true(max(abs(vcov(fit)-vcov(reference))) < 1e-7)
  expect_identical(fit[["projection_diagnostics"]][[2L]][["status"]], "completed")
})
