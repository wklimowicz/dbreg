local({
  conn = DBI::dbConnect(duckdb::duckdb())
  on.exit(DBI::dbDisconnect(conn, shutdown = TRUE))
  set.seed(11170)
  d = expand.grid(g = 1:4, x = -1:1, rep = 1:12)
  d$id = seq_len(nrow(d))
  d$w = runif(nrow(d), .2, 2)
  d$o = cos(d$rep)/10
  d$y = 1 + .4*d$x + sin(d$g) + d$o + rnorm(nrow(d))
  for (weighted in c(FALSE, TRUE)) for (strategy in c("moments", "demean", "compress")) {
    absorbed = strategy != "moments"
    dense = lm(if (absorbed) y ~ x + factor(g) else y ~ x, data = d,
      weights = if (weighted) w else rep(1, nrow(d)), offset = o)
    fit = dbreg(if (absorbed) y ~ x | g else y ~ x, conn = conn, data = d,
      weights = if (weighted) ~w, offset = ~o, strategy = strategy, retain = "all")
    n = nobs(dense)
    expected = -n/2 * (1 + log(sum(residuals(dense)^2)/n) + log(2*pi))
    likelihood = logLik(fit)
    expect_equal(as.numeric(likelihood),expected,tolerance=1e-10)
    expect_equal(df.residual(fit),df.residual(dense))
    expect_equal(attr(likelihood,"df"),dense$rank+1)
    expect_equal(attr(likelihood,"nobs"),n)
    expect_equal(AIC(fit),-2*expected+2*(dense$rank+1))
    expect_equal(BIC(fit),-2*expected+log(n)*(dense$rank+1))
    if (weighted) expect_true(abs(as.numeric(likelihood)-as.numeric(logLik(dense)))>1e-3)
    expect_equal(nrow(dbreg::augment(fit)),n)
    close(fit)
    expect_identical(logLik(fit),likelihood)
    expect_identical(DBI::dbListTables(conn),character())
  }
  fit = dbreg(y~x,data=d,weights=~w)
  expect_error(logLik(fit),"requires retain")
  d$count = rpois(nrow(d),exp(.2+.3*d$x))
  glm = dbglm(count~x,data=d,family=poisson())
  dense = stats::glm(count~x,data=d,family=poisson())
  expect_equal(df.residual(glm),df.residual(dense))
  expect_equal(predict(glm,d),unname(predict(dense,type="link")),tolerance=1e-8)
  expect_equal(predict(glm,d,type="response"),unname(fitted(dense)),tolerance=1e-8)
  expect_error(confint(glm,fe=TRUE),"Absorbed-effect confidence")
  DBI::dbWriteTable(conn,"source",d,temporary=TRUE)
  fit = dbreg(y~x,conn=conn,table="source",row_id="id",retain="inference")
  rows = fitted(fit)
  result = predict(fit,conn=conn,table="source",row_id="id")
  close(fit);close(rows);close(result)
  expect_true(length(capture.output(print(rows)))<5L)
  expect_true(length(capture.output(print(result)))<5L)
  expect_identical(DBI::dbListTables(conn),"source")
})
